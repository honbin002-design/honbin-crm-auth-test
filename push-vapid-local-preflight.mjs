// Pure WebCrypto/VAPID shape and static privacy proof; synthetic keys only.
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
import {spawnSync} from 'node:child_process';
import {webcrypto} from 'node:crypto';
const html=readFileSync('push-vapid-local-setup.html','utf8');
assert.match(html,/<html lang="zh-Hant">/);
assert.match(html,/Content-Security-Policy/);
assert.match(html,/connect-src 'none'/);
assert.match(html,/default-src 'none'/);
assert.match(html,/TEST_VAPID_PUBLIC_KEY/);
assert.match(html,/TEST_VAPID_PRIVATE_KEY/);
assert.match(html,/TEST_PUSH_CONTACT/);
assert.match(html,/TEST_PUSH_SEND_ENABLED/);
const inline=html.match(/<script>([\s\S]*?)<\/script>/)?.[1];
assert.ok(inline,'browser-only script must exist');
const syntax=spawnSync(process.execPath,['--check'],{input:inline,encoding:'utf8'});
assert.equal(syntax.status,0,syntax.stderr);
assert.doesNotMatch(inline,/\bfetch\s*\(|\bsendBeacon\s*\(|\bXMLHttpRequest\b|\bWebSocket\s*\(|\bimport\s*\(/);
assert.doesNotMatch(inline,/\blocalStorage\s*[.[(]|\bindexedDB\s*[.[(]/);
assert.doesNotMatch(html,/<script[^>]+src=|<link[^>]+stylesheet/i);
const keys=await webcrypto.subtle.generateKey({name:'ECDSA',namedCurve:'P-256'},true,['sign','verify']);
const publicBytes=new Uint8Array(await webcrypto.subtle.exportKey('raw',keys.publicKey));
const secret=(await webcrypto.subtle.exportKey('jwk',keys.privateKey)).d;
const encode=bytes=>Buffer.from(bytes).toString('base64url');
const publicVapid=encode(publicBytes);
assert.equal(publicBytes.length,65);
assert.equal(publicBytes[0],4);
assert.match(publicVapid,/^[-_A-Za-z0-9]{87}$/);
assert.match(secret,/^[-_A-Za-z0-9]{43}$/);
const rebuiltPublic=await webcrypto.subtle.importKey('raw',publicBytes,{name:'ECDSA',namedCurve:'P-256'},false,['verify']);
const msg=new TextEncoder().encode('synthetic-only');
const sig=await webcrypto.subtle.sign({name:'ECDSA',hash:'SHA-256'},keys.privateKey,msg);
assert.equal(await webcrypto.subtle.verify({name:'ECDSA',hash:'SHA-256'},rebuiltPublic,sig,msg),true);
